def paper_L_basis():
    """Doubled coordinates of the paper's Appendix-A basis L_1..L_8."""
    B = [S2[:]]
    B.append([2, 2, 0, 0, 0, 0, 0, 0])
    B.append([2, -2, 0, 0, 0, 0, 0, 0])
    for k in range(2, 7):
        v = [2, 0, 0, 0, 0, 0, 0, 0]
        v[k] = 2
        B.append(v)
    return B


LB = paper_L_basis()                              # rows = doubled vectors
LB_INV = frac_inverse(LB)                         # X = c . LB  <=>  c = X . LB_INV
LB_NP = np.array(LB, dtype=np.int64)


def Lcoords(X, allow_fail=False):
    """Integer L-coordinates of a doubled vector X (asserts integrality)."""
    c = [sum(Fraction(int(X[i])) * LB_INV[i][k] for i in range(8)) for k in range(8)]
    if any(t.denominator != 1 for t in c):
        if allow_fail:
            return None
        raise AssertionError("vector not in L: %s" % (list(X),))
    return [int(t) for t in c]


def from_Lcoords(c):
    """Doubled e-coordinates of sum_k c_k L_k."""
    return [int(sum(int(c[k]) * LB[k][i] for k in range(8))) for i in range(8)]


def structure_constants(T=T_STD):
    """C[i,j,:] = L-coordinates of L_i . L_j under the table T."""
    C = np.zeros((8, 8, 8), dtype=np.int64)
    for i in range(8):
        for j in range(8):
            C[i, j] = Lcoords(dmul(LB[i], LB[j], T))
    return C


C_STD = structure_constants()                     # this is the paper's Table LL


def Ls_basis_L():
    """L-coordinates of L_k.s (k = 1..8): a basis of Ls."""
    return [Lcoords(dmul(LB[k], S2)) for k in range(8)]


def Lsbar_basis_L():
    """L-coordinates of L_k.sbar: a basis of Lsbar (sbar not in L, product is)."""
    out = []
    for k in range(8):
        P = omul(LB[k], SBAR2)          # (2L_k)(2 sbar) = 4 L_k sbar
        assert all(p % 2 == 0 for p in P)
        out.append(Lcoords([p // 2 for p in P]))
    return out


