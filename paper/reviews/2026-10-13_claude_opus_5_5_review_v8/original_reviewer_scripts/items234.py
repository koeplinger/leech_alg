def is_aut(M, TT):
    # M(e_a e_b) == M(e_a) M(e_b) for all a,b
    lhs = np.einsum('abc,dc->abd', TT, M)                          # M applied to products
    rhs = np.einsum('ia,jb,ijk->abk', M, M, TT)                     # products of images
    return (lhs == rhs).all()
