"""Wilson's sublattices and the maximal orders of the octonions (paper v8:
Section 1, the seven maximal orders; Section 7, the structural reason for
Lemma 4.3).  Prompt 289, 14 October 2026.

Conventions are the paper's: the multiplication (2.1) (octonions.py), L = D_8^+
with s = (-e0 + e1 + ... + e7)/2 in L, Wilson's sublattices formed with left
multiples, L sbar = {l . sbar} and L s = {l . s}, and sigma = (1 2).  Exact
arithmetic throughout (fractions.Fraction; integer Hermite normal forms).

Note (15 October 2026): the paper's Section 1 (v8) states (A) as "the integral
octonions have exactly seven maximal orders containing the Gravesian order
Z<e0, ..., e7>, each an E_8 lattice"; the wording below is the mathematical
statement behind it.  Code and output unchanged.
Updated 15 October 2026 (prompt 304): Section 1 now reads "seven maximal
orders of integral octonions contain all eight basis units, each an E_8
lattice"; containing the eight units is containing Z<e0, ..., e7>.

(A) Section 1.  For the multiplication (2.1), exactly seven maximal orders of
    the rational octonions contain the Gravesian order Z<e0, ..., e7>, each a
    scaled copy of the E_8 lattice.  Reduction to a finite check (standard):
    in an order every element has an integral trace t(x) = 2 x_0, so for x in
    an order containing every e_i, t(x . conj(e_i)) = 2 <x, e_i> is an integer
    and x lies in (1/2)Z^8.  Such an order is Z^8 + C/2 for a binary code C,
    and integral norms force C to be doubly even.  The script enumerates all
    doubly-even codes of length 8 (each such code gives a candidate lattice
    containing Z^8 with integral norms and traces), keeps those whose lattice
    is closed under (2.1), and finds: exactly 7 closed lattices with |C| = 16,
    each unimodular for the trace form 2<,> (hence a maximal order), and every
    closed lattice contained in one of the 7.  So the maximal orders
    containing Z<e0..e7> are exactly these 7.  (The 30 doubly-even codes with
    |C| = 16 are the images of one extended Hamming code under the coordinate
    permutations; checked against the enumeration.)
(B) The 7 are O^(n) = Z^8 + (0 n)C_K/2, n = 1..7, where C_K is generated by
    the all-ones word and the words {0} u l over the seven Fano lines l of
    (2.1); J_1 := Z^8 + C_K/2, the analogue of Kirmse's set for (2.1), is
    stable under the 16 units but not closed.
(C) L is contained in each O^(n).
(D) L sbar = 2 J_1, L = J_1 . s, L s = J_1 . s^2, and sigma(L sbar) = 2 O^(4);
    2 O^(n) does not contain sigma(L sbar) for n != 4.
(E) Lemma 4.3, both sides, checked directly on the basis products:
    L . sigma(L sbar) and sigma(L sbar) . L lie in sigma(L sbar).  It also
    follows from (A), (C), (D): L lies in O = O^(4), and O . O lies in O.
(F) sigma(L s) = p O^(4) with p = e2 - e4 + e5 - e6, of norm 4.
(G) [2 O^(4) : <2 O^(4) . 2 O^(4)>] = 2^8, the factor h_V of sigma's span
    index 2^16 = h_W . h_V^2 (h_W = 1 and the formula:
    verify_twist_span_index_census.py, Theorem B).

Usage: python3 verify_sigma_sublattice_maximal_order.py   (a few seconds)

Updated 20 October 2026 (prompt 311): cited in Section 2.2 (v8) for the closure
and maximality of O = O^(4) = (1/2)(e1 + e2) L; the Section 7 paragraph moved
into Section 4.  Code and output unchanged.
"""
import itertools
from fractions import Fraction as F

from octonions import STANDARD_FANO_TRIPLES as FANO
from verify_consecutive_twists_exact import Lb, s, sbar, inL
from verify_ideal_decomposition import omul
from verify_twist_span_index_census import hnf_det

E = [[F(1) if j == i else F(0) for j in range(8)] for i in range(8)]
ip = lambda a, b: sum(x * y for x, y in zip(a, b))
sig = lambda x: [x[0], x[2], x[1]] + list(x[3:])


def span_code(gens):
    code = {(0,) * 8}
    for g in gens:
        code |= {tuple((a + b) % 2 for a, b in zip(c, g)) for c in code}
    return frozenset(code)


def in_ZC(v, code, scale=1):
    """v in scale * (Z^8 + C/2)?"""
    w = [x / scale for x in v]
    if any((2 * x).denominator != 1 for x in w):
        return False
    return tuple(int(2 * x) % 2 for x in w) in code


def gens_ZC(code, scale=1):
    return [[scale * x for x in e] for e in E] + [[F(scale * c, 2) for c in w] for w in code]


def covolume(vectors, denom=4):
    """|det| of the lattice spanned by vectors with coordinates in (1/denom)Z."""
    rows = [[int(denom * x) for x in v] for v in vectors]
    assert all(F(denom) * x == int(denom * x) for v in vectors for x in v)
    return F(hnf_det(rows, 8), denom ** 8)


def coords(v, basis):
    n = 8
    M = [[basis[j][i] for j in range(n)] + [v[i]] for i in range(n)]
    for c in range(n):
        p = next(r for r in range(c, n) if M[r][c] != 0)
        M[c], M[p] = M[p], M[c]
        pv = M[c][c]
        M[c] = [x / pv for x in M[c]]
        for r in range(n):
            if r != c and M[r][c] != 0:
                f = M[r][c]
                M[r] = [a - f * b for a, b in zip(M[r], M[c])]
    return [M[i][n] for i in range(n)]


def in_span(v, basis):
    return all(c.denominator == 1 for c in coords(v, basis))


def main():
    ok = True
    # ------------------------------------------------------------- (A), (B)
    C_K = span_code([[1] * 8] + [[1 if i in (0,) + tuple(l) else 0 for i in range(8)] for l in FANO])
    codes = {frozenset(tuple(c[p[i]] for i in range(8)) for c in C_K) for p in itertools.permutations(range(8))}
    closed = [C for C in codes if all(in_ZC(omul(a, b), C) for a in gens_ZC(C) for b in gens_ZC(C))]
    print("(A) doubly-even self-dual codes of length 8:", len(codes), "| lattices Z^8 + C/2 closed under (2.1):", len(closed))
    ok &= len(codes) == 30 and len(closed) == 7
    unimod = True
    for C in closed:
        g = gens_ZC(C)
        integral = all((2 * ip(a, b)).denominator == 1 for a in g for b in g) and all(ip(a, a).denominator == 1 for a in g)
        unimod &= integral and covolume(g) ** 2 * 2 ** 8 == 1          # det of the trace form 2<,> is 1
    print("    each closed one: integral norms and trace form, det(2<,>) = 1 (unimodular, hence maximal):", unimod)
    ok &= unimod
    # every doubly-even code of length 8, by closure under adding doubly-even words
    words = [w for w in itertools.product((0, 1), repeat=8) if sum(w) % 4 == 0]
    all_codes, frontier = {frozenset({(0,) * 8})}, [frozenset({(0,) * 8})]
    while frontier:
        nxt = []
        for C in frontier:
            for w in words:
                if w in C:
                    continue
                D = frozenset(C | {tuple((a + b) % 2 for a, b in zip(c, w)) for c in C})
                if D not in all_codes and all(sum(d) % 4 == 0 for d in D):
                    all_codes.add(D)
                    nxt.append(D)
        frontier = nxt
    closed_all = [C for C in all_codes if all(in_ZC(omul(a, b), C) for a in gens_ZC(C) for b in gens_ZC(C))]
    inside = all(any(C <= M for M in closed) for C in closed_all)
    size16 = {C for C in all_codes if len(C) == 16} == codes
    print("    all doubly-even codes:", len(all_codes), "| those with |C| = 16 are the 30 above:", size16,
          "| with closed lattice Z^8 + C/2:", len(closed_all),
          "| each inside one of the 7:", inside, "=> exactly 7 maximal orders contain Z<e0..e7>")
    ok &= size16 and inside
    swap = lambda c, n: tuple(c[n] if i == 0 else c[0] if i == n else c[i] for i in range(8))
    O = {n: frozenset(swap(c, n) for c in C_K) for n in range(1, 8)}
    print("(B) the closed ones are O^(n) = Z^8 + (0 n)C_K/2, n = 1..7:", set(closed) == set(O.values()))
    ok &= set(closed) == set(O.values())
    units = [[sgn * x for x in e] for e in E for sgn in (1, -1)]
    J1_closed = all(in_ZC(omul(a, b), C_K) for a in gens_ZC(C_K) for b in gens_ZC(C_K))
    J1_unit_stable = all(in_ZC(omul(u, g), C_K) and in_ZC(omul(g, u), C_K) for u in units for g in gens_ZC(C_K))
    print("    J_1 = Z^8 + C_K/2: stable under the 16 units", J1_unit_stable, "| closed", J1_closed)
    ok &= J1_unit_stable and not J1_closed
    # ------------------------------------------------------------- (C)
    c_ok = all(in_ZC(b, O[n]) for n in O for b in Lb)
    print("(C) L is contained in every O^(n):", c_ok)
    ok &= c_ok
    # ------------------------------------------------------------- (D)
    Lsbar = [omul(b, sbar) for b in Lb]
    Ls = [omul(b, s) for b in Lb]
    sLsbar = [sig(v) for v in Lsbar]
    sLs = [sig(v) for v in Ls]
    d1 = all(in_ZC(v, C_K, 2) for v in Lsbar) and covolume(Lsbar) == covolume(gens_ZC(C_K, 2))
    d2 = all(in_ZC(v, O[4], 2) for v in sLsbar) and covolume(sLsbar) == covolume(gens_ZC(O[4], 2))
    others = [n for n in O if n != 4 and all(in_ZC(v, O[n], 2) for v in sLsbar)]
    J1s = [omul(g, s) for g in gens_ZC(C_K)]
    J1ss = [omul(g, omul(s, s)) for g in gens_ZC(C_K)]
    d3 = all(inL(v) for v in J1s) and covolume(J1s) == covolume(Lb)
    d4 = all(in_span(v, Ls) for v in J1ss) and covolume(J1ss) == covolume(Ls)
    print("(D) L sbar = 2 J_1:", d1, "| L = J_1 . s:", d3, "| L s = J_1 . s^2:", d4)
    print("    sigma(L sbar) = 2 O^(4):", d2, "| other n with sigma(L sbar) in 2 O^(n):", others)
    ok &= d1 and d2 and d3 and d4 and not others
    # ------------------------------------------------------------- (E)
    e_ok = all(in_span(omul(a, v), sLsbar) and in_span(omul(v, a), sLsbar) for a in Lb for v in sLsbar)
    print("(E) Lemma 4.3, both sides: L . sigma(L sbar) and sigma(L sbar) . L inside sigma(L sbar):", e_ok)
    ok &= e_ok
    # ------------------------------------------------------------- (F)
    p = [F(0)] * 8
    p[2], p[4], p[5], p[6] = F(1), F(-1), F(1), F(-1)
    pO = [omul(p, g) for g in gens_ZC(O[4])]
    f_ok = ip(p, p) == 4 and in_ZC(p, O[4]) and all(in_span(v, sLs) for v in pO) and covolume(pO) == covolume(sLs)
    print("(F) N(p) =", ip(p, p), "| p in O^(4):", in_ZC(p, O[4]), "| sigma(L s) = p O^(4):", f_ok)
    ok &= f_ok
    # ------------------------------------------------------------- (G)
    twoO = gens_ZC(O[4], 2)
    prods = [omul(a, b) for a in twoO for b in twoO]
    h = covolume(prods) / covolume(twoO)
    print("(G) [2 O^(4) : <2 O^(4) . 2 O^(4)>] =", h, "= 2^8:", h == 256)
    ok &= h == 256
    print("ALL PASS" if ok else "FAILURE")


if __name__ == "__main__":
    main()
