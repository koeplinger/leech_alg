def perm_map(pi):
    """g_pi on doubled vectors: g(e0) = e0, g(e_a) = e_{pi(a)}; pi = (pi(1..7))."""
    def f(X):
        Y = [0] * 8
        Y[0] = X[0]
        for a in range(1, 8):
            Y[pi[a - 1]] = X[a]
        return Y
    return f


def perm_inverse(pi):
    inv = [0] * 7
    for a in range(1, 8):
        inv[pi[a - 1] - 1] = a
    return tuple(inv)


def reflection_map(R):
    """s_r on doubled vectors, R = 2r (r a root): s_r(x) = x - <x,r> r."""
    def f(X):
        ip = sum(int(a) * int(b) for a, b in zip(X, R))     # = 4 <x,r>
        assert ip % 4 == 0, "<x,r> not an integer"
        k = ip // 4
        return [int(a) - k * int(b) for a, b in zip(X, R)]
    return f


def gamma_of(fmap):
    """Integer matrix of g in the L-basis (row convention), asserting g(L) = L."""
    G = [Lcoords(fmap(LB[i])) for i in range(8)]
    d = int_det(G)
    assert abs(d) == 1, "g does not preserve L"
    return np.array(G, dtype=np.int64)


def gamma_inverse(G):
    Gi = frac_inverse(G.tolist())
    assert all(x.denominator == 1 for row in Gi for x in row)
    return np.array([[int(x) for x in row] for row in Gi], dtype=np.int64)


def twisted_constants(G, C=C_STD):
    """C_g[i,j,:] = L-coordinates of L_i ._g L_j = g^{-1}(g L_i . g L_j)."""
    Gi = gamma_inverse(G)
    Cg = np.einsum('ip,jq,pqc,ck->ijk', G, G, C, Gi)
    return assert_small(Cg)


def twisted_table_e(fmap, finv):
    """For maps sending basis vectors to signed basis vectors: the twisted
    multiplication table T_g[a,b,c] (e-basis), computed from the definition."""
    E = [[2 * int(i == j) for j in range(8)] for i in range(8)]   # doubled e_i
    Tg = np.zeros((8, 8, 8), dtype=np.int64)
    for a in range(8):
        for b in range(8):
            Z = finv(dmul(fmap(E[a]), fmap(E[b])))
            Tg[a, b] = [z // 2 for z in Z]
    return Tg


