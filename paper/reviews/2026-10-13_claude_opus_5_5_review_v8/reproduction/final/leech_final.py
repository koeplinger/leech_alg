INT64_SAFE = 2**40          # every int64 array we create must stay below this


def assert_small(a, bound=INT64_SAFE):
    a = np.asarray(a)
    if a.size:
        m = int(np.abs(a).max())
        assert m < bound, "int64 bound exceeded: %d" % m
    return a


def egcd(a, b):
    """(g, x, y) with x*a + y*b = g = gcd(a, b) >= 0 (Python ints)."""
    x0, y0, x1, y1 = 1, 0, 0, 1
    while b:
        q = a // b
        a, b = b, a - q * b
        x0, x1 = x1, x0 - q * x1
        y0, y1 = y1, y0 - q * y1
    if a < 0:
        a, x0, y0 = -a, -x0, -y0
    return a, x0, y0


def frac_inverse(M):
    """Exact inverse of a square integer/rational matrix (list of lists) as Fractions."""
    n = len(M)
    A = [[Fraction(x) for x in row] + [Fraction(int(i == j)) for j in range(n)]
         for i, row in enumerate(M)]
    for c in range(n):
        p = next(r for r in range(c, n) if A[r][c] != 0)
        A[c], A[p] = A[p], A[c]
        pv = A[c][c]
        A[c] = [x / pv for x in A[c]]
        for r in range(n):
            if r != c and A[r][c] != 0:
                f = A[r][c]
                A[r] = [x - f * y for x, y in zip(A[r], A[c])]
    return [row[n:] for row in A]


def int_det(M):
    """Exact determinant of an integer matrix (Bareiss fraction-free elimination)."""
    A = [[int(x) for x in row] for row in M]
    n = len(A)
    sign, prev = 1, 1
    for k in range(n - 1):
        if A[k][k] == 0:
            sw = next((r for r in range(k + 1, n) if A[r][k] != 0), None)
            if sw is None:
                return 0
            A[k], A[sw] = A[sw], A[k]
            sign = -sign
        for i in range(k + 1, n):
            for j in range(k + 1, n):
                A[i][j] = (A[i][j] * A[k][k] - A[i][k] * A[k][j]) // prev
        prev = A[k][k]
    return sign * A[n - 1][n - 1]


def hnf(rows, n):
    """Exact row-style Hermite normal form of the Z-span of `rows` (each of
    length n).  Pure Python integers, unimodular row operations only, no
    modular reduction.  Returns the list of nonzero HNF rows (upper triangular,
    positive pivots, entries above a pivot reduced into [0, pivot))."""
    piv = {}
    for r in rows:
        v = [int(t) for t in r]
        j = 0
        while j < n:
            if v[j] == 0:
                j += 1
                continue
            if j not in piv:
                if v[j] < 0:
                    v = [-t for t in v]
                piv[j] = v
                break
            h = piv[j]
            g, x, y = egcd(h[j], v[j])
            a, b = h[j] // g, v[j] // g
            piv[j] = [x * hh + y * vv for hh, vv in zip(h, v)]
            v = [a * vv - b * hh for hh, vv in zip(h, v)]
            j += 1
        # keep entries small: reduce every row modulo the later pivots
        cols = sorted(piv)
        for k in cols:
            pk = piv[k]
            for i in cols:
                if i >= k:
                    break
                q = piv[i][k] // pk[k]
                if q:
                    piv[i] = [a - q * b for a, b in zip(piv[i], pk)]
    return [piv[k] for k in sorted(piv)]


def hnf_index(rows, n):
    """[Z^n : span(rows)] via the exact HNF; None if the span has rank < n."""
    H = hnf(rows, n)
    if len(H) < n:
        return None, H
    idx = 1
    for k, row in enumerate(H):
        idx *= row[k]
    return idx, H


