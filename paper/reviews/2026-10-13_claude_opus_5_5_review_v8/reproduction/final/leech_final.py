def bil(U, V, C):
    return np.einsum('pa,qb,abc->pqc', U, V, C)


def triple_products(B, C):
    """All products b_p * b_q (p = LEFT factor) for the rows of B (L^3-coords),
    with block structure constants C.  Returns a (n*n, 24) array, row p*n+q."""
    X, Y, Z = B[:, 0:8], B[:, 8:16], B[:, 16:24]
    P1 = bil(X, X, C) + bil(Z, Y, C) + bil(Y, Z, C)
    P2 = bil(Y, Y, C) + bil(X, Z, C) + bil(Z, X, C)
    P3 = bil(Z, Z, C) + bil(Y, X, C) + bil(X, Y, C)
    P = np.concatenate([P1, P2, P3], axis=2)
    n = B.shape[0]
    return assert_small(P.reshape(n * n, 24))


def lambda_coords(P, N):
    """Lambda-coordinates of products P (L^3-coords).  Returns (coords, ok_mask)."""
    Q = assert_small(P @ N)
    ok = np.all(Q % 2 == 0, axis=1)
    return Q // 2, ok


def mod2_ok(P, cond):
    return np.all((cond @ (P.T % 2)) % 2 == 0, axis=0)


def index_z4(coords):
    """[Lambda : S] from the Z/4 structure, VALID WHEN 4 Lambda <= S (proved for
    every twist g in Aut(L), see f2_witnesses.py).  Returns (index, r2, a, b)."""
    r2 = f2_rank(coords)
    a, b = z4_structure(coords)
    n = coords.shape[1]
    return 2 ** (2 * n - 2 * a - b), r2, a, b


def h_index(Ub_L, C):
    """h(U~) = [U~ : Z-span(U~ . U~)] for the full preimage U~ in L of an
    F2-subspace U (basis rows in L-coords mod 2), product with constants C.
    Returns (h, HNF of span in L-coords, basis of U~)."""
    # basis of U~: lifts of RREF rows + 2 e_j for non-pivot columns
    R, piv = f2_rref(np.array(Ub_L, dtype=np.int64))
    U = [list(map(int, r)) for r in R]
    for j in range(8):
        if j not in piv:
            e = [0] * 8
            e[j] = 2
            U.append(e)
    U = np.array(U, dtype=np.int64)
    prods = bil(U, U, C).reshape(64, 8)
    H = hnf(prods.tolist(), 8)
    idxU, _ = hnf_index(U.tolist(), 8)
    idxS, _ = hnf_index(prods.tolist(), 8)
    if idxS is None:
        return None, H, U
    assert idxS % idxU == 0
    return idxS // idxU, H, U


