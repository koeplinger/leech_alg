#!/bin/sh
# extract_paper_tables.sh
# Reads the three 64-row coefficient tables of Appendix A of the paper
# (main.tex, read-only) and writes them as GAP lists to paper_tables.g:
#   PAPER_TABLE_LL[n] = [i, j, c1..c8]  with  L_i . L_j = sum_k c_k L_k
#   PAPER_TABLE_LN[n] = [i, j, c1..c8]  with  L_i . N_j = sum_k c_k N_k
#   PAPER_TABLE_MM[n] = [i, j, c1..c8]  with  M_i . M_j = sum_k c_k M_k
# Line ranges are those of the three table environments in v8 main.tex.
TEX=${1:-../../../../main.tex}
OUT=${2:-paper_tables.g}
emit () {  # $1 = GAP name, $2 = first line, $3 = last line
  printf '%s := [\n' "$1"
  awk -v a="$2" -v b="$3" 'NR>=a && NR<=b' "$TEX" \
    | command grep -E '^[1-8] & [1-8] &' \
    | sed -e 's/\\\\.*$//' -e 's/&/,/g' -e 's/^/  [/' -e 's/ *$/],/'
  printf '];\n'
}
{
  echo "# generated by extract_paper_tables.sh from $TEX"
  emit PAPER_TABLE_LL 1233 1327
  emit PAPER_TABLE_LN 1329 1423
  emit PAPER_TABLE_MM 1425 1519
} > "$OUT"
