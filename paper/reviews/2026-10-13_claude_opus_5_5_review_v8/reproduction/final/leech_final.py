def f2_span_basis(rows):
    R, piv = f2_rref(np.array(rows, dtype=np.int64))
    return R


def annihilator(Vbasis):
    """Rows a with a.v = 0 (dot product over F2) for all v in V: t in V iff A t = 0."""
    return f2_nullspace(np.array(Vbasis, dtype=np.int64))


def wilson_lattice_basis(Vb, Wb):
    """Z-basis (24x24 integer, L^3-coordinates) of
         Lambda(V,W) = {(x,y,z) in L^3 : x+y, x+z, y+z in V~ ; x+y+z in W~},
    V~, W~ the full preimages in L of the F2-subspaces V, W of L/2L (given by
    basis rows in L-coordinates mod 2).  Built from the RREF of the kernel K
    of the mod-2 conditions: lifts of the RREF rows plus 2 e_j for every
    non-pivot column j; this spans the full preimage of K and has det 2^(24-dim K)."""
    AV = annihilator(Vb)
    AW = annihilator(Wb)
    I8 = np.eye(8, dtype=np.int64)
    Z8 = np.zeros((8, 8), dtype=np.int64)
    blocks = []
    for (P, Q, R) in ((I8, I8, Z8), (I8, Z8, I8), (Z8, I8, I8)):
        blocks.append(np.hstack([AV @ P, AV @ Q, AV @ R]))
    blocks.append(np.hstack([AW, AW, AW]))
    cond = np.vstack(blocks) % 2
    K = f2_nullspace(cond)
    R, piv = f2_rref(K)
    basis = [list(map(int, r)) for r in R]
    for j in range(24):
        if j not in piv:
            e = [0] * 24
            e[j] = 2
            basis.append(e)
    B = np.array(basis, dtype=np.int64)
    return B, cond


def lattice_inverse2(B):
    """N = 2 B^{-1} as an integer matrix (valid because 2 Z^24 is in rowspan(B))."""
    Binv = frac_inverse(B.tolist())
    N = [[2 * x for x in row] for row in Binv]
    assert all(x.denominator == 1 for row in N for x in row)
    return np.array([[int(x) for x in row] for row in N], dtype=np.int64)


class Setup:
    """Everything built from the definitions: L, Ls, Lsbar, Lambda."""

    def __init__(self):
        self.C = C_STD
        self.Ls_L = Ls_basis_L()
        self.Lsbar_L = Lsbar_basis_L()
        self.W0 = f2_span_basis(self.Ls_L)        # Ls/2L
        self.V0 = f2_span_basis(self.Lsbar_L)     # Lsbar/2L
        assert len(self.W0) == 4 and len(self.V0) == 4
        self.B, self.cond = wilson_lattice_basis(self.V0, self.W0)
        self.N = lattice_inverse2(self.B)         # Lambda coords = P @ N / 2

    # Lambda basis in doubled e-coordinates
    def basis_e(self):
        out = []
        for row in self.B:
            out.append(sum((from_Lcoords(row[8 * k:8 * k + 8]) for k in range(3)), []))
        return out


