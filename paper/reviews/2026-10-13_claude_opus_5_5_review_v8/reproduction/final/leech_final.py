def f2_rref(M):
    """Reduced row echelon form over F2. Returns (R, pivot_columns)."""
    A = (np.array(M, dtype=np.int64) % 2).astype(np.uint8)
    m, n = A.shape
    piv, r = [], 0
    for c in range(n):
        if r == m:
            break
        nz = np.nonzero(A[r:, c])[0]
        if len(nz) == 0:
            continue
        p = r + nz[0]
        if p != r:
            A[[r, p]] = A[[p, r]]
        others = np.nonzero(A[:, c])[0]
        others = others[others != r]
        A[others] ^= A[r]
        piv.append(c)
        r += 1
    return A[:r], piv


def f2_rank(M):
    return len(f2_rref(M)[1])


def f2_nullspace(M):
    """Basis (rows) of {x : M x = 0} over F2."""
    M = np.array(M, dtype=np.int64) % 2
    n = M.shape[1]
    R, piv = f2_rref(M)
    free = [c for c in range(n) if c not in piv]
    basis = []
    for f in free:
        x = np.zeros(n, dtype=np.uint8)
        x[f] = 1
        for i, pc in enumerate(piv):
            x[pc] = R[i, f]
        basis.append(x)
    return np.array(basis, dtype=np.uint8).reshape(len(basis), n)


def z4_structure(R):
    """Structure of the subgroup H of (Z/4)^n generated by the rows of R:
    H = (Z/4)^a x (Z/2)^b.  Returns (a, b).  Smith-type elimination over the
    local ring Z/4 (unit pivots first, then the F2-rank of the 2-divisible
    remainder).  Then |(Z/4)^n / H| = 2^(2n-2a-b) and
    (Z/4)^n / H = (Z/2)^b x (Z/4)^(n-a-b)."""
    A = np.array(R, dtype=np.int64) % 4
    m, n = A.shape
    rows_free = np.ones(m, bool)
    cols_free = np.ones(n, bool)
    a = 0
    while True:
        odd = (A % 2 == 1) & rows_free[:, None] & cols_free[None, :]
        idx = np.argwhere(odd)
        if len(idx) == 0:
            break
        i, j = idx[0]
        A[i] = (A[i] * (1 if A[i, j] == 1 else 3)) % 4      # 3 = 3^{-1} mod 4
        f = A[:, j].copy()
        f[i] = 0
        A = (A - np.outer(f, A[i])) % 4                      # clear column j
        A[i] = 0                                             # column ops clear row i
        A[i, j] = 1
        rows_free[i] = False
        cols_free[j] = False
        a += 1
    rest = A[rows_free][:, cols_free]
    assert np.all(rest % 2 == 0)
    b = f2_rank(rest // 2) if rest.size else 0
    return a, b


