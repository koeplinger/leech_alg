"""
leech_final.py -- exact-arithmetic library for the final (skeptic) review of
J. Koeplinger, "An order on the Leech lattice from a Z3-symmetric
triple-octonion product" (v8).  Written from the paper's definitions only.

CONVENTIONS (every script in this folder imports them from here)
----------------------------------------------------------------
Octonions.  O = R^8 with basis e0..e7, e0 the identity.  Fano triples
    (1,2,4),(2,3,5),(3,4,6),(4,5,7),(5,6,1),(6,7,2),(7,1,3):
    for a triple (a,b,c): e_a e_b = e_c, e_b e_c = e_a, e_c e_a = e_b, and the
    reversed orders carry a minus sign; e_i^2 = -e0 for i >= 1.

Doubled coordinates.  Every vector of (1/2)Z^8 is stored as the INTEGER vector
    X = 2x of its doubled e-coordinates.  If X = 2x and Y = 2y then 2(xy) = (X.Y)/2.

L = D8+ (odd convention).  x in L  iff  all x_i in Z with sum even, or all
    x_i in Z+1/2 with sum ODD.  In doubled coordinates: all X_i even and
    sum(X) = 0 mod 4, or all X_i odd and sum(X) = 2 mod 4.

s = (-e0+e1+...+e7)/2 (in L), sbar = (-e0-...-e7)/2 (not in L).
    Ls = {l.s : l in L},  Lsbar = {l.sbar : l in L}   (l is the LEFT factor).
    Definitional membership test used below (from (x y) ybar = N(y) x, N(s) = 2):
        t in Lsbar  <=>  (t.s)/2 in L,        t in Ls  <=>  (t.sbar)/2 in L.

L-coordinates.  The paper's Appendix-A basis L_1..L_8 of L:
    L1 = s, L2 = e0+e1, L3 = e0-e1, L_{k+2} = e0+e_k (k = 2..6).
    A vector x in L has integer L-coordinates c with x = sum_k c_k L_k.

Leech lattice (Wilson):  Lambda = {(x,y,z) in L^3 : x+y, x+z, y+z in Lsbar;
    x+y+z in Ls}.  Stored in L^3-coordinates (24 integers).

Twists.  A twist is a linear map g of R^8 with g(L) = L; the twisted product is
        x ._g y := g^{-1}( g(x) . g(y) ).
    * Coordinate permutation pi of {1..7}, written as the tuple
      (pi(1),...,pi(7)), acts by g_pi(e0) = e0, g_pi(e_a) = e_{pi(a)}.  Then
      x ._pi y = pi^{-1}(pi(x).pi(y)), exactly the paper's Section 5.6 product.
      "Convention A" twists by g_pi, "convention B" twists by g_pi^{-1}.
      Example: the 3-cycle e5 -> e6 -> e7 -> e5 is the tuple (1,2,3,4,6,7,5).
    * Root reflection s_r(x) = x - <x,r> r for a root r (<r,r> = 2).  It is an
      involution, so g = g^{-1} and no direction convention arises.
    * In L-coordinates g is an integer unimodular matrix Gam (row convention):
      g(L_i) = sum_k Gam[i,k] L_k.

Triple product (Def. 3.3).  For u = (x,y,z) (LEFT factor) and v = (x',y',z'):
        P1 = x x' + z y' + y z',  P2 = y y' + x z' + z x',  P3 = z z' + y x' + x y',
    every block product being ._g.

Span index.  S_g = Z-span{u *_g v : u, v in Lambda}, generated by the 576
    basis-pair products b_p *_g b_q (p = left, q = right).  [Lambda : S_g] is
    computed from their integer Lambda-coordinates.

Arithmetic.  Python integers and fractions.Fraction throughout; numpy int64 is
    used only for small structure-constant arithmetic and every result that
    passes through int64 is bounded explicitly (assert_small) well below 2^62.
"""

