FANO = [(1, 2, 4), (2, 3, 5), (3, 4, 6), (4, 5, 7), (5, 6, 1), (6, 7, 2), (7, 1, 3)]


def octonion_table(fano=FANO):
    """T[a,b,c] = coefficient of e_c in e_a e_b."""
    T = np.zeros((8, 8, 8), dtype=np.int64)
    for a in range(8):
        T[0, a, a] = 1
        T[a, 0, a] = 1
    for a in range(1, 8):
        T[a, a, 0] = -1
    for (a, b, c) in fano:
        for (p, q, r) in ((a, b, c), (b, c, a), (c, a, b)):
            T[p, q, r] = 1
            T[q, p, r] = -1
    assert np.all(np.abs(T).sum(axis=2) == 1)       # every e_a e_b = +-e_c
    return T


T_STD = octonion_table()


def omul(x, y, T=T_STD):
    """Octonion product of vectors with arbitrary (int or Fraction) entries."""
    z = [0] * 8
    for a in range(8):
        if x[a] == 0:
            continue
        for b in range(8):
            if y[b] == 0:
                continue
            for c in range(8):
                t = T[a, b, c]
                if t:
                    z[c] += int(t) * x[a] * y[b]
    return z


def dmul(X, Y, T=T_STD):
    """Product in doubled coordinates: returns 2(xy) for X = 2x, Y = 2y (exact)."""
    Z = omul(list(map(int, X)), list(map(int, Y)), T)
    assert all(t % 2 == 0 for t in Z), "product not in (1/2)Z^8"
    return [t // 2 for t in Z]


def conj(X):
    return [X[0]] + [-t for t in X[1:]]


def norm2(X):
    """Norm N(x) = sum x_i^2 of x = X/2, as a Fraction."""
    return Fraction(sum(int(t) * int(t) for t in X), 4)


def in_L(X):
    """X = doubled coordinates.  D8+ in the odd convention."""
    X = [int(t) for t in X]
    s = sum(X)
    if all(t % 2 == 0 for t in X):
        return s % 4 == 0
    if all(t % 2 != 0 for t in X):
        return s % 4 == 2
    return False


S2 = [-1, 1, 1, 1, 1, 1, 1, 1]        # 2s
SBAR2 = [-1, -1, -1, -1, -1, -1, -1, -1]  # 2 sbar


def in_Lsbar_def(X):
    """t in Lsbar  <=>  (t.s)/2 in L   (definitional; t given doubled)."""
    P = omul(list(map(int, X)), S2)            # = 4 (t.s) in doubled units: (2t)(2s) = 4ts
    # doubled coordinates of (t.s)/2 are 2*(t.s)/2 = t.s = P/4
    if any(p % 4 for p in P):
        return False
    return in_L([p // 4 for p in P])


def in_Ls_def(X):
    """t in Ls  <=>  (t.sbar)/2 in L   (definitional; t given doubled)."""
    P = omul(list(map(int, X)), SBAR2)
    if any(p % 4 for p in P):
        return False
    return in_L([p // 4 for p in P])


def in_Lambda_def(U):
    """Wilson's definition, straight from the paper (U = 24 doubled e-coords)."""
    x, y, z = list(U[0:8]), list(U[8:16]), list(U[16:24])
    add = lambda a, b: [int(p) + int(q) for p, q in zip(a, b)]
    if not (in_L(x) and in_L(y) and in_L(z)):
        return False
    if not (in_Lsbar_def(add(x, y)) and in_Lsbar_def(add(x, z)) and in_Lsbar_def(add(y, z))):
        return False
    return in_Ls_def(add(add(x, y), z))


